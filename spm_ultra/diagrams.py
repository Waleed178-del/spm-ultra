"""Generate the workflow charts in /workflows from the registry (single source of truth).

Run:  spm-ultra --write-diagrams        or        python -m spm_ultra.diagrams
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

from .registry import (DEPENDENCIES, DIRECTORATES, MANDATORY_CROSS_CHECKS, REFERENCES,
                       agent_by_id, directorate_of, downstream, mesh_edges, tag, upstream)

HEADER = "<!-- GENERATED by spm_ultra/diagrams.py. Do not edit by hand: run `spm-ultra --write-diagrams`. -->\n\n"

PALETTE = {
    1: "#4C78A8", 2: "#F58518", 3: "#54A24B", 4: "#E45756", 5: "#72B7B2", 6: "#B279A2",
}


def _label(text: str) -> str:
    return text.replace("&", "and").replace('"', "'")


def _node(aid: int) -> str:
    return f'{tag(aid)}["{tag(aid)} {_label(agent_by_id(aid).name)}"]'


def _class_defs() -> str:
    lines = [f"    classDef d{d} fill:{c},stroke:#222,color:#fff" for d, c in PALETTE.items()]
    for d in DIRECTORATES:
        lines.append(f"    class {','.join(tag(a.id) for a in d.agents)} d{d.id}")
    return "\n".join(lines)


def _mermaid(body: str) -> str:
    return f"```mermaid\n{body.rstrip()}\n```\n"


# --------------------------------------------------------------------------- 01 topology


def topology() -> str:
    lines = ["flowchart TB", '    M(["Master Orchestrator"])']
    for d in DIRECTORATES:
        lines.append(f'    L{d.id}{{{{"Lead D{d.id}: {_label(d.name)}"}}}}')
        lines.append(f"    M <--> L{d.id}")
        lines.append(f'    subgraph D{d.id}["Directorate {d.id} ({d.agent_range})"]')
        lines.append("        direction TB")
        for a in d.agents:
            lines.append(f"        {_node(a.id)}")
        lines.append("    end")
        for a in d.agents:
            lines.append(f"    L{d.id} <--> {tag(a.id)}")
    lines.append(_class_defs())
    return HEADER + f"""# 01. Cluster Topology

The command hierarchy: 1 Master Orchestrator, 6 directorate leads, 30 specialists.
Every specialist reports up through exactly one lead. The master never reads raw specialist output except through reconciliation (see [06](06-contradiction-audit.md)).

{_mermaid(chr(10).join(lines))}
| Directorate | Lead | Agents | Blueprint section |
|---|---|---|---|
""" + "\n".join(
        f"| D{d.id} | Lead D{d.id} | {', '.join(tag(a.id) for a in d.agents)} | {d.section_title} |"
        for d in DIRECTORATES
    ) + "\n"


# --------------------------------------------------------------------------- 02 lifecycle


def lifecycle() -> str:
    flow = """flowchart TD
    U[/"User idea"/] --> I{"Intake gate<br/>goal, timeline, budget present?"}
    I -- "no" --> Q[/"3 diagnostic questions<br/>exit code 2"/]
    Q -. "--answers" .-> I
    I -- "yes" --> CB["Normalized context brief"]
    CB --> P2["Phase 2: parallel dispatch<br/>A01 to A30 run concurrently"]
    P2 --> MR{"--mesh-rounds > 0?"}
    MR -- "yes" --> P3["Phase 3: mesh round<br/>each agent reads its upstream peers<br/>and revises"]
    P3 --> MR2{"more rounds?"}
    MR2 -- "yes" --> P3
    MR2 -- "no" --> P4
    MR -- "no" --> P4["Phase 4: 6 directorate leads<br/>internal refinement, consolidated briefs"]
    P4 --> P5["Phase 5: contradiction audit<br/>structured JSON over 6 briefs"]
    P5 --> C{"live conflicts?"}
    C -- "yes" --> R["Reconciliation loops<br/>only the conflicting agents' raw output"]
    C -- "no" --> P6
    R --> P6["Phase 6: Master Feasibility Blueprint<br/>Sections I to VIII, every claim tagged A##"]
    P6 --> OUT[/"runs/&lt;timestamp&gt;/"/]"""
    return HEADER + f"""# 02. Run Lifecycle

{_mermaid(flow)}
## Call budget per run

| Phase | Calls | Parallel | Effort flag |
|---|---|---|---|
| 1 Intake | 1 | no | medium (fixed) |
| 2 Dispatch | 30 | yes | `--worker-effort` |
| 3 Mesh round | 30 per round | yes | `--worker-effort` |
| 4 Leads | 6 | yes | `--lead-effort` |
| 5 Audit | 1 | no | `--master-effort` |
| 5 Reconcile | 0 to {len(MANDATORY_CROSS_CHECKS)}+ | yes | `--lead-effort` |
| 6 Blueprint | 1 | no | `--master-effort` |

Default total: about 40 calls. With `--mesh-rounds 1`: about 70.
Each phase waits for the previous phase to finish, so wall time is about 4 to 5 sequential steps, not 40.
"""


# --------------------------------------------------------------------------- 03 protocol


def protocol() -> str:
    seq = """sequenceDiagram
    autonumber
    actor U as User
    participant M as Master Orchestrator
    participant S as Specialists A01-A30
    participant P as Upstream peers
    participant L as Leads D1-D6
    participant X as Auditor
    participant R as Reconcilers
    U->>M: raw_idea (+ diagnostic_answers)
    M->>M: intake (JSON schema)
    alt baseline missing
        M-->>U: 3 diagnostic questions
    end
    par 30 concurrent calls
        M->>S: context_brief
        S-->>M: specialist markdown (tags A##)
    end
    opt --mesh-rounds N
        loop each round
            M->>S: context_brief + your_previous_output + upstream_peer_outputs
            P-->>S: (peer outputs routed by Master, not direct)
            S-->>M: revised markdown + Alignment Notes
        end
    end
    par 6 concurrent calls
        M->>L: context_brief + 5 specialist_outputs
        L-->>M: directorate brief
    end
    M->>X: context_brief + 6 briefs
    X-->>M: conflicts[] (JSON schema)
    par one call per live conflict
        M->>R: conflict + raw output of involved agents only
        R-->>M: reconciled position
    end
    M->>M: blueprint from briefs + audit + reconciliations
    M-->>U: blueprint.md + run folder"""
    return HEADER + f"""# 03. Communication Protocol

Agents never call each other directly. Every message is routed by the Master Orchestrator, which decides what each node is allowed to see. This is how the cluster avoids token bloat and directive conflicts.

{_mermaid(seq)}
## Message envelopes

| # | Sender | Receiver | Envelope (XML tags in the user turn) | Format |
|---|---|---|---|---|
| 1 | User | Intake | `<raw_idea>`, `<diagnostic_answers>` | text |
| 2 | Intake | Master | `ready`, `context_brief`, `diagnostic_questions` | JSON schema |
| 3 | Master | Specialist | `<context_brief>` | text |
| 4 | Specialist | Master | `### A##: Name` + Findings, Assumptions, Recommendations, Cross-Dependencies, References | markdown |
| 5 | Master | Specialist (mesh) | `<context_brief>`, `<your_previous_output>`, `<upstream_peer_outputs><peer tag="A##">` | text |
| 6 | Master | Lead | `<context_brief>`, `<specialist_outputs><agent id name>` | text |
| 7 | Lead | Master | Directorate brief with Key Numbers table | markdown |
| 8 | Master | Auditor | `<context_brief>`, `<brief directorate="N">` x6 | text |
| 9 | Auditor | Master | `conflicts[]`: check, agent_ids, in_conflict, severity, description | JSON schema |
| 10 | Master | Reconciler | `<conflict>`, `<agent id name>` for involved agents only | text |
| 11 | Master | Blueprint | briefs, `<audit>`, `<reconciliations>` | text |

## Visibility rules

| Node | Sees | Never sees |
|---|---|---|
| Specialist (pass 1) | context brief | any other agent |
| Specialist (mesh) | context brief, own output, its upstream peers only | non upstream agents |
| Lead | its 5 specialists | other directorates |
| Auditor | 6 briefs | raw specialist output |
| Reconciler | raw output of the conflicting agents | everything else |
| Blueprint | briefs, audit, reconciliations | raw specialist output |

## Referencing convention

Every agent has a tag `A01` to `A30`. Agents must cite peers as `[A12]`, and the blueprint must tag every material claim with its source agents, e.g. `[A06, A12]`. This makes any number in the blueprint traceable back to `runs/<ts>/agents/agent_12.md`.
"""


# --------------------------------------------------------------------------- 04 mesh


def mesh() -> str:
    edges = mesh_edges()
    lines = ["flowchart LR"]
    for d in DIRECTORATES:
        lines.append(f'    subgraph D{d.id}["D{d.id} {_label(d.name)}"]')
        for a in d.agents:
            lines.append(f"        {_node(a.id)}")
        lines.append("    end")
    for src, dst in edges:
        lines.append(f"    {tag(src)} --> {tag(dst)}")
    lines.append(_class_defs())

    cross = Counter(
        (directorate_of(s).id, directorate_of(t).id) for s, t in edges
        if directorate_of(s).id != directorate_of(t).id
    )
    dl = ["flowchart LR"]
    for d in DIRECTORATES:
        dl.append(f'    D{d.id}["D{d.id} {_label(d.name)}"]')
    for (s, t), n in sorted(cross.items()):
        dl.append(f'    D{s} -- "{n}" --> D{t}')
    for d in DIRECTORATES:
        dl.append(f"    style D{d.id} fill:{PALETTE[d.id]},color:#fff")

    ids = [a.id for d in DIRECTORATES for a in d.agents]
    header = "| from \\ to | " + " | ".join(f"{i:02d}" for i in ids) + " |"
    sep = "|---|" + "---|" * len(ids)
    rows = [
        f"| **{tag(s)}** | " + " | ".join("●" if s in DEPENDENCIES[t] else "" for t in ids) + " |"
        for s in ids
    ]
    intra = sum(1 for s, t in edges if directorate_of(s).id == directorate_of(t).id)
    return HEADER + f"""# 04. Agent Mesh Network

The hierarchy in [01](01-cluster-topology.md) is the command path. This page is the **information mesh**: which specialist must read and align with which other specialist. An arrow `A12 --> A13` means A13 consumes A12's output.

The mesh is used in three places:
1. Every specialist's system prompt lists its upstream and downstream peers, so it states exactly what it needs and what it supplies.
2. With `--mesh-rounds N`, each specialist re-reads its upstream peers' actual output and revises (see [03](03-communication-protocol.md)).
3. Leads and the auditor use the `[A##]` cross-dependency tags to find contradictions.

**Stats:** 30 nodes, {len(edges)} directed edges ({intra} within a directorate, {len(edges) - intra} across directorates). A literal full mesh would be 870 directed edges; the cluster deliberately wires only the dependencies that carry real numbers or decisions.

## Full agent mesh

{_mermaid(chr(10).join(lines))}
## Directorate level mesh (edge label = number of agent links)

{_mermaid(chr(10).join(dl))}
## Adjacency matrix

Row = producer, column = consumer. `●` means the column agent reads the row agent.

{header}
{sep}
""" + "\n".join(rows) + "\n"


# --------------------------------------------------------------------------- 05 directorate flows


def directorate_flows() -> str:
    parts = [HEADER, "# 05. Directorate Internal Flows\n\n"
             "Each directorate runs its 5 specialists in parallel, optionally revises them through the mesh, "
             "then its lead runs the internal refinement loop. Dotted nodes are peers in other directorates.\n"]
    for d in DIRECTORATES:
        own = {a.id for a in d.agents}
        ext_in = sorted({u for a in own for u in upstream(a) if u not in own})
        ext_out = sorted({x for a in own for x in downstream(a) if x not in own})
        lines = ["flowchart LR", '    CB[/"context brief"/]']
        lines.append(f'    subgraph IN["D{d.id} specialists"]')
        for a in d.agents:
            lines.append(f"        {_node(a.id)}")
        lines.append("    end")
        lines.append(f'    LEAD{{{{"Lead D{d.id}<br/>refinement loop"}}}}')
        lines.append('    BRIEF[/"Directorate brief"/]')
        lines.append('    M(["Master"])')
        for a in d.agents:
            lines.append(f"    CB --> {tag(a.id)}")
            lines.append(f"    {tag(a.id)} --> LEAD")
        lines.append("    LEAD --> BRIEF --> M")
        for u in ext_in:
            lines.append(f'    X{tag(u)}["{tag(u)} {_label(agent_by_id(u).name)}"]:::ext')
        for x in ext_out:
            if x not in ext_in:
                lines.append(f'    X{tag(x)}["{tag(x)} {_label(agent_by_id(x).name)}"]:::ext')
        for a in sorted(own):
            for u in upstream(a):
                if u in own:
                    lines.append(f"    {tag(u)} --> {tag(a)}")
                else:
                    lines.append(f"    X{tag(u)} -.-> {tag(a)}")
            for x in downstream(a):
                if x not in own:
                    lines.append(f"    {tag(a)} -.-> X{tag(x)}")
        lines.append("    classDef ext fill:#eee,stroke:#999,stroke-dasharray:4 3,color:#333")
        lines.append(f"    classDef own fill:{PALETTE[d.id]},stroke:#222,color:#fff")
        lines.append(f"    class {','.join(tag(a.id) for a in d.agents)} own")
        parts.append(f"\n## D{d.id}: {d.name} ({d.agent_range})\n\n"
                     f"Output feeds **{d.section_title}**.\n\n{_mermaid(chr(10).join(lines))}")
    return "".join(parts)


# --------------------------------------------------------------------------- 06 audit


def audit_flow() -> str:
    lines = ["flowchart TD", '    B[/"6 directorate briefs"/] --> X{"Auditor<br/>JSON schema"}']
    for i, (name, a, b) in enumerate(MANDATORY_CROSS_CHECKS, 1):
        left = ", ".join(tag(x) for x in a)
        right = ", ".join(tag(x) for x in b)
        lines.append(f'    X --> C{i}["{_label(name)}<br/>{left} vs {right}"]')
        lines.append(f'    C{i} --> K{i}{{"in conflict?"}}')
        lines.append(f'    K{i} -- "yes" --> R{i}["Reconcile: raw output of {left}, {right}"]')
        lines.append(f'    K{i} -- "no" --> OK{i}["logged as consistent"]')
        lines.append(f"    R{i} --> BP")
        lines.append(f"    OK{i} --> BP")
    lines.append('    X --> O["any other material conflict found"] --> BP')
    lines.append('    BP[["Blueprint Section VII:<br/>Contradiction Audit Log"]]')
    return HEADER + f"""# 06. Contradiction Audit and Reconciliation

The auditor always evaluates the mandatory cross checks below, and reports any other material conflict it finds. Each live conflict spawns one reconciliation call, which receives the **raw** output of only the agents involved. Reconciled figures override the directorate briefs in the final blueprint.

{_mermaid(chr(10).join(lines))}
| # | Check | Side A | Side B |
|---|---|---|---|
""" + "\n".join(
        f"| {i} | {name} | {', '.join(tag(x) for x in a)} | {', '.join(tag(x) for x in b)} |"
        for i, (name, a, b) in enumerate(MANDATORY_CROSS_CHECKS, 1)
    ) + "\n\nAdd checks in `MANDATORY_CROSS_CHECKS` in `spm_ultra/registry.py`, then regenerate.\n"


# --------------------------------------------------------------------------- 07 reference cards


def reference_cards() -> str:
    out = [HEADER, "# 07. Agent Reference Cards\n\nOne card per specialist: mandate, canonical references, mesh links and audit exposure. "
           "Test any single agent with `spm-ultra --agent N \"your idea\"`.\n"]
    for d in DIRECTORATES:
        out.append(f"\n## D{d.id}: {d.name}\n")
        for a in d.agents:
            checks = [n for n, x, y in MANDATORY_CROSS_CHECKS if a.id in (*x, *y)]
            ups = ", ".join(f"[{tag(u)}] {agent_by_id(u).name}" for u in upstream(a.id)) or "none"
            downs = ", ".join(f"[{tag(x)}] {agent_by_id(x).name}" for x in downstream(a.id)) or "none"
            refs = "; ".join(REFERENCES[a.id])
            out.append(
                f"\n### {tag(a.id)}: {a.name}\n\n"
                f"| Field | Value |\n|---|---|\n"
                f"| Mandate | {a.mandate} |\n"
                f"| References | {refs} |\n"
                f"| Reads from (upstream) | {ups} |\n"
                f"| Feeds (downstream) | {downs} |\n"
                f"| Audit cross checks | {'; '.join(checks) or 'none'} |\n"
                f"| Output file | `runs/<ts>/agents/agent_{a.id:02d}.md` |\n"
                f"| Test command | `spm-ultra --agent {a.id} \"idea\"` |\n"
            )
    return "".join(out)


# --------------------------------------------------------------------------- index


def index() -> str:
    return HEADER + """# Workflows

Charts of how SPM Ultra's 31 nodes (1 master, 6 leads, 30 specialists) are wired and how they communicate. GitHub renders the Mermaid blocks inline.

| File | Shows |
|---|---|
| [01-cluster-topology.md](01-cluster-topology.md) | Command hierarchy: master, leads, specialists |
| [02-run-lifecycle.md](02-run-lifecycle.md) | End to end flow of one run and the call budget |
| [03-communication-protocol.md](03-communication-protocol.md) | Sequence diagram, message envelopes, visibility rules, referencing convention |
| [04-agent-mesh.md](04-agent-mesh.md) | Full agent to agent dependency mesh, directorate mesh, adjacency matrix |
| [05-directorate-flows.md](05-directorate-flows.md) | Inside each directorate, with links to peers in other directorates |
| [06-contradiction-audit.md](06-contradiction-audit.md) | Cross checks and reconciliation loops |
| [07-agent-reference.md](07-agent-reference.md) | One card per agent: mandate, references, links, test command |

## Two networks, not one

1. **Command network (hierarchy).** Who sends work to whom. Strict tree, routed by the master.
2. **Information network (mesh).** Whose output each agent must align with. Defined in `DEPENDENCIES`, used in prompts and in `--mesh-rounds`.

All messages on both networks pass through the master. No agent calls another agent directly.

## Regenerate

These files are generated from `spm_ultra/registry.py`. After changing agents, references, dependencies or cross checks:

```bash
spm-ultra --write-diagrams
```

The test suite fails if the charts are stale.
"""


FILES = {
    "README.md": index,
    "01-cluster-topology.md": topology,
    "02-run-lifecycle.md": lifecycle,
    "03-communication-protocol.md": protocol,
    "04-agent-mesh.md": mesh,
    "05-directorate-flows.md": directorate_flows,
    "06-contradiction-audit.md": audit_flow,
    "07-agent-reference.md": reference_cards,
}


def render_all() -> dict[str, str]:
    return {name: fn() for name, fn in FILES.items()}


def write_all(out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, text in render_all().items():
        path = out_dir / name
        path.write_text(text)
        paths.append(path)
    return paths


if __name__ == "__main__":
    for p in write_all(Path(sys.argv[1] if len(sys.argv) > 1 else "workflows")):
        print(p)
