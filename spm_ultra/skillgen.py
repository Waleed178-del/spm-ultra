"""Generate the Claude Code skill's reference files from the registry and prompts.

The hand written entry point is skills/spm-ultra/SKILL.md. Everything under
skills/spm-ultra/references/ is generated here so the skill never drifts from the code.

Run:  spm-ultra --write-skill        or        python -m spm_ultra.skillgen
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from . import prompts
from .registry import (DIRECTORATES, MANDATORY_CROSS_CHECKS, Agent, agent_by_id, directorate_of,
                       downstream, tag, upstream)

HEADER = "<!-- GENERATED by spm_ultra/skillgen.py. Do not edit: run `spm-ultra --write-skill`. -->\n\n"

SKILL_DATA_RULE = (
    "If the orchestrator told you WEB MODE IS ON, use the WebSearch and WebFetch tools for current "
    "market data, prices and regulation, and cite every external figure with its source URL. "
    "If WEB MODE IS OFF, do not browse: mark any market figure as ASSUMED and say what source "
    "would confirm it."
)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def agent_file(a: Agent) -> str:
    return f"agents/{tag(a.id)}-{slug(a.name)}.md"


def directorate_file(d) -> str:
    return f"directorates/D{d.id}-{d.key}.md"


# --------------------------------------------------------------------------- files


def agent_doc(a: Agent) -> str:
    d = directorate_of(a.id)
    return HEADER + f"""# {tag(a.id)}: {a.name}

Directorate D{d.id}: {d.name}. Upstream: {', '.join(tag(u) for u in upstream(a.id))}. Downstream: {', '.join(tag(x) for x in downstream(a.id))}.

## System prompt

Adopt the following as your operating instructions for this analysis.

{prompts.agent_system(a, d, data_rule=SKILL_DATA_RULE)}
"""


def directorate_doc(d) -> str:
    rows = "\n".join(f"| {tag(a.id)} | {a.name} | `references/{agent_file(a)}` |" for a in d.agents)
    return HEADER + f"""# D{d.id}: {d.name} ({d.agent_range})

Feeds blueprint **{d.section_title}**.

## Specialists

| Tag | Agent | Instructions |
|---|---|---|
{rows}

## Directorate subagent procedure (standard mode)

You are running all five specialists of this directorate, then acting as its lead.

1. For each specialist above, in order: read its instruction file, then write its full analysis of the context brief exactly in its output format. Stay strictly inside that specialist's mandate. Do not let one specialist's conclusions leak into the next one's analysis; each must stand alone.
2. Save each analysis to `<run_dir>/agents/agent_NN.md` (NN = two digit agent number).
3. Now act as the lead using the prompt below. Resolve conflicts between your five specialists and write the consolidated brief.
4. Save the brief to `<run_dir>/briefs/directorate_{d.id}.md`.
5. Return to the orchestrator ONLY: the brief text, nothing else.

## Lead prompt

{prompts.directorate_lead_system(d)}
"""


def mesh_doc() -> str:
    rows = "\n".join(
        f"| {tag(a.id)} | {a.name} | {', '.join(tag(u) for u in upstream(a.id))} | "
        f"{', '.join(tag(x) for x in downstream(a.id))} |"
        for d in DIRECTORATES for a in d.agents
    )
    revision = prompts.mesh_revision_user("<context brief>", "<contents of agents/agent_NN.md>", {})
    revision = revision.replace(
        "<upstream_peer_outputs>\n\n</upstream_peer_outputs>",
        '<upstream_peer_outputs>\n<peer tag="A##" name="...">\n<contents of agents/agent_##.md>\n'
        "</peer>\n(one peer block per upstream agent)\n</upstream_peer_outputs>")
    return HEADER + f"""# Agent Mesh

Who reads whom. Used by mesh rounds (`--mesh`, full mode only) and by agents to tag cross-dependencies.

| Agent | Name | Reads (upstream) | Feeds (downstream) |
|---|---|---|---|
{rows}

## Mesh revision task (one per agent)

Give the agent subagent its instruction file plus this task, with real file contents substituted:

```
{revision}
```

Before overwriting `agents/agent_NN.md`, copy the first pass to `agents/first_pass/agent_NN.md`.
"""


def intake_doc() -> str:
    return HEADER + f"""# Intake Gate

{prompts.intake_system()}

Return (in your own working notes, not to the user unless questions are needed) these fields:

```json
{json.dumps(prompts.INTAKE_SCHEMA["properties"], indent=2)}
```

Save the result as `<run_dir>/intake.json`.

If `ready` is false: show the user the three diagnostic questions and STOP. Do not dispatch any agent.
"""


def audit_doc() -> str:
    checks = "\n".join(
        f"- {name}: agents {list(a)} vs agents {list(b)}" for name, a, b in MANDATORY_CROSS_CHECKS
    )
    return HEADER + f"""# Contradiction Audit

{prompts.audit_system(checks)}

Input: the context brief and the six files `<run_dir>/briefs/directorate_1.md` to `directorate_6.md`.

Output: save to `<run_dir>/audit.json` a JSON object matching this schema:

```json
{json.dumps(prompts.AUDIT_SCHEMA, indent=2)}
```

Then, for every item with `in_conflict: true`, run a reconciliation (see `reconcile.md`).
"""


def reconcile_doc() -> str:
    return HEADER + f"""# Reconciliation Loop

For each live conflict, give the reconciler the conflict JSON and the RAW files `<run_dir>/agents/agent_NN.md` of ONLY the agents in `agent_ids`. Do not give it the briefs.

## Reconciler prompt

{prompts.reconcile_system()}

Append every result to `<run_dir>/reconciliations.md`. Reconciled figures override the directorate briefs in the blueprint.
"""


def blueprint_doc() -> str:
    return HEADER + f"""# Master Feasibility Blueprint

Input: context brief, six directorate briefs, `audit.json`, `reconciliations.md`. Do not re-read the 30 raw agent files unless a claim must be verified.

## Master prompt

{prompts.master_system()}

Save to `<run_dir>/blueprint.md`, then show it to the user.
"""


def index_doc() -> str:
    agents = "\n".join(
        f"| {tag(a.id)} | {a.name} | D{directorate_of(a.id).id} | `{agent_file(a)}` |"
        for d in DIRECTORATES for a in d.agents
    )
    dirs = "\n".join(f"| D{d.id} | {d.name} | `{directorate_file(d)}` |" for d in DIRECTORATES)
    return HEADER + f"""# Reference Index

| File | Use |
|---|---|
| `intake.md` | Phase 1 intake gate |
| `directorates/*.md` | Standard mode: one subagent per directorate |
| `agents/*.md` | Full mode: one subagent per specialist |
| `mesh.md` | Mesh round and peer links |
| `audit.md` | Contradiction audit |
| `reconcile.md` | Reconciliation loops |
| `blueprint.md` | Final dossier format |

## Directorates

| ID | Name | File |
|---|---|---|
{dirs}

## Agents

| Tag | Name | Directorate | File |
|---|---|---|---|
{agents}
"""


def render_all() -> dict[str, str]:
    files = {
        "README.md": index_doc(),
        "intake.md": intake_doc(),
        "mesh.md": mesh_doc(),
        "audit.md": audit_doc(),
        "reconcile.md": reconcile_doc(),
        "blueprint.md": blueprint_doc(),
    }
    for d in DIRECTORATES:
        files[directorate_file(d)] = directorate_doc(d)
        for a in d.agents:
            files[agent_file(a)] = agent_doc(a)
    return files


def write_all(skill_dir: Path) -> list[Path]:
    ref = skill_dir / "references"
    paths = []
    for rel, text in render_all().items():
        path = ref / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        paths.append(path)
    return paths


if __name__ == "__main__":
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "skills/spm-ultra")
    for p in write_all(out):
        print(p)
